// THE LENGTH OF THE LONGEST WELL-FORMED UTF-8 PREFIX OF `text` THAT IS AT MOST
// `limit` BYTES. Zero for a body that starts with a continuation byte or an
// over-long form.
//
// It exists so that shortening happens at a code-point boundary and nowhere
// else: a Russian phrase is about two bytes a letter and a single emoji is four,
// so a byte budget cut with `substr` splits a character roughly half the time in
// this product's second language. The send path does not call it to repair
// anything -- over budget is a refusal the owner sees before sending, never a
// silent truncation -- it calls it to decide whether the body it was handed is
// well formed at all.
//
// The algorithm is MeshCore's `mesh::validUtf8PrefixLength`
// (`src/helpers/UTF8Helpers.h` at `d929643`, MIT), which is unused at that
// revision: this is an extracted algorithm and not a dependency on a firmware
// this product does not link.
std::size_t utf8_prefix_length(std::string_view text, std::size_t limit);

